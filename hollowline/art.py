def phone(lines, ring=0):
    """A phone with `lines` on its screen. `ring` toggles the vibration waves."""
    inner = 17
    body = [
        "╭─────────────────────╮",
        "│  ▪    ●    ▬▬▬▬     │",
        "│ ┌─────────────────┐ │",
    ]
    content = list(lines) + [""] * (9 - len(lines))
    for ln in content[:9]:
        body.append("│ │" + ln.center(inner)[:inner] + "│ │")
    body += [
        "│ └─────────────────┘ │",
        "│          ◯          │",
        "╰─────────────────────╯",
    ]
    if ring:
        waves = ["(((  ", " ((( ", "  (((", " ((( "][ring % 4]
        wavesr = ["  )))", " ))) ", ")))  ", " ))) "][ring % 4]
        out = []
        for i, ln in enumerate(body):
            if 4 <= i <= 10:
                out.append(waves + " " + ln + " " + wavesr)
            else:
                out.append("      " + ln + "      ")
        return out
    return ["      " + ln + "      " for ln in body]


