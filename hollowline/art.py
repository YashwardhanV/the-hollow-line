"""Hand-drawn ASCII art for THE HOLLOW LINE."""


def _block(s):
    lines = s.split("\n")
    while lines and not lines[0].strip():
        lines.pop(0)
    while lines and not lines[-1].strip():
        lines.pop()
    w = max(len(l) for l in lines)
    return [l.ljust(w) for l in lines]


